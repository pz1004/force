"""Plot measured contamination diagnostics; no breakdown guarantee is inferred.

Input is the named JSON report from scripts/run_algorithm_diagnostics.py.
Historical paper figures are archival and are not regenerated by this script.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd


PANEL_COLUMNS = [
    "scenario", "mode", "fraction_parameter", "fraction_unit", "observation_order",
]
IDENTITY_COLUMNS = [
    "protocol", "estimator", "quantile_backend", "execution_schedule",
    "comparison_target", "clean_reference_target", "n_samples", "n_features",
    "window_size", "calibration_rows", "policy_parameters",
]
POLICY_STYLES = {
    "uncapped": ("#9467bd", "o", "-"),
    "capped": ("#1f77b4", "s", "--"),
    "fixed": ("#d62728", "^", ":"),
}


def diagnostic_frame(report: dict) -> pd.DataFrame:
    """Validate provenance and retain failures instead of silently dropping them."""
    if report.get("status") != "completed":
        raise ValueError("A completed diagnostic report is required; inspect failed cases first.")
    rows = report.get("results")
    if not isinstance(rows, list) or not rows:
        raise ValueError("Diagnostic report must contain nonempty results.")
    frame = pd.DataFrame(rows)
    required = set(PANEL_COLUMNS + [
        "protocol", "status", "bound_policy", "contamination_magnitude", "seed", "run_id",
        "estimator", "quantile_backend", "execution_schedule", "comparison_target",
        "clean_reference_target", "n_samples", "n_features", "policy_parameters",
        "clean_target_rmse",
    ])
    missing = required - set(frame.columns)
    if missing:
        raise ValueError(f"Diagnostic report is missing fields: {sorted(missing)}")
    if frame[list(required)].isna().any().any():
        raise ValueError("Required diagnostic fields cannot be missing.")
    online = frame["mode"].eq("online")
    if online.any():
        for name in ("window_size", "calibration_rows"):
            if name not in frame or frame.loc[online, name].isna().any():
                raise ValueError(f"Online results require {name} metadata.")
    if not frame["status"].eq("completed").all():
        raise ValueError("Diagnostic report contains incomplete or failed cases.")
    if "clean_target_score" in frame:
        for score in frame["clean_target_score"]:
            if not isinstance(score, dict) or score.get("status") != "complete":
                raise ValueError("Diagnostic comparison has incomplete pair coverage; do not silently compare different pair sets.")
    if not frame["clean_reference_target"].eq("known_clean_population_Pearson").all():
        raise ValueError("This plot requires the named known-clean population Pearson target.")
    if frame["protocol"].nunique(dropna=False) != 1:
        raise ValueError("Do not combine different protocols in a diagnostic figure.")
    if not frame["protocol"].eq(report.get("protocol")).all():
        raise ValueError("Report and result protocol identities must agree.")
    for name in ("fraction_parameter", "contamination_magnitude", "clean_target_rmse"):
        frame[name] = pd.to_numeric(frame[name], errors="raise")
        if not np.isfinite(frame[name]).all():
            raise ValueError(f"Diagnostic field {name} must be finite.")
    if (frame["contamination_magnitude"] <= 0).any() or (frame["clean_target_rmse"] < 0).any():
        raise ValueError("Contamination magnitudes must be positive and RMSE nonnegative.")
    if ((frame["fraction_parameter"] < 0) | (frame["fraction_parameter"] > 1)).any():
        raise ValueError("Contamination fractions must lie in [0, 1].")
    if frame["bound_policy"].isna().any() or not set(frame["bound_policy"]).issubset(POLICY_STYLES):
        raise ValueError("Unknown bound policy in diagnostic report.")
    frame["policy_parameters"] = frame["policy_parameters"].map(
        lambda value: json.dumps(value, sort_keys=True, allow_nan=False)
    )
    # Curves aggregate independent seeds, never distinct algorithms, schedules,
    # targets, sample sizes, or bound policies under the same name.
    for _, group in frame.groupby(PANEL_COLUMNS + ["bound_policy"], dropna=False):
        for name in IDENTITY_COLUMNS:
            if name in group and group[name].nunique(dropna=False) != 1:
                raise ValueError(f"Mixed diagnostic identity for {name}; split reports before plotting.")
    for _, group in frame.groupby(PANEL_COLUMNS, dropna=False):
        for name in ("n_samples", "n_features", "execution_schedule", "comparison_target"):
            if group[name].nunique(dropna=False) != 1:
                raise ValueError(f"Mixed diagnostic identity for {name} within a panel.")
    sample_keys = PANEL_COLUMNS + ["bound_policy", "contamination_magnitude", "seed"]
    if frame.duplicated(sample_keys).any():
        raise ValueError("Duplicate diagnostic sample identities would overweight observations.")
    return frame


def create_diagnostic_figures(report: dict, output_dir: Path) -> list[Path]:
    """Save measured plots, retaining every recorded outcome.

    Points are means over the report's independent data seeds. No confidence
    interval or population breakdown point is inferred from these observations.
    """
    frame = diagnostic_frame(report)
    output_dir.mkdir(parents=True, exist_ok=True)
    outputs = []
    for index, (condition, group) in enumerate(frame.groupby(PANEL_COLUMNS, sort=True, dropna=False), 1):
        scenario, mode, fraction, unit, order = condition
        with plt.rc_context({"font.family": "DejaVu Sans", "font.size": 9, "axes.titlesize": 10}):
            fig, ax = plt.subplots(figsize=(7.1, 4.3), layout="constrained")
            for policy, policy_group in group.groupby("bound_policy", sort=False):
                measured = policy_group.groupby("contamination_magnitude")["clean_target_rmse"].agg(["mean", "count"]).sort_index()
                color, marker, linestyle = POLICY_STYLES[policy]
                counts = sorted(measured["count"].unique())
                count_label = str(counts[0]) if len(counts) == 1 else f"{counts[0]}–{counts[-1]}"
                parameters = json.loads(policy_group["policy_parameters"].iloc[0])
                policy_label = {"uncapped": "TER uncapped", "fixed": "Fixed bounds (no TER)"}.get(
                    policy, f"TER cap={parameters.get('ter_max')}"
                )
                ax.plot(measured.index, measured["mean"], color=color, marker=marker,
                        linestyle=linestyle, label=f"{policy_label} (n={count_label} seeds)")
            ax.set_xscale("log")
            ax.set_ylim(0, max(float(group["clean_target_rmse"].max()) * 1.1, 1e-8))
            ax.set_xlabel("Contamination magnitude (generator parameter)")
            ax.set_ylabel("Off-diagonal RMSE vs clean population Pearson")
            title = f"{scenario.replace('_', ' ')} | {mode} | {order.replace('_', ' ')}\n"
            title += f"Contamination parameter: {100 * fraction:g}% of {unit}; "
            title += f"N={int(group['n_samples'].iloc[0])}, p={int(group['n_features'].iloc[0])}"
            if mode == "online":
                title += f"\nPrevious-window bounds (W={int(group['window_size'].iloc[0])}); calibration excluded"
            ax.set_title(title)
            ax.grid(alpha=0.2)
            ax.legend(loc="best", fontsize=8)
            fig.supxlabel("Measured cases only; these errors do not establish a breakdown guarantee.", fontsize=8)
            stem = f"contamination_diagnostic_{index:03d}"
            for suffix in ("png", "pdf"):
                path = output_dir / f"{stem}.{suffix}"
                fig.savefig(path, dpi=200)
                outputs.append(path)
            plt.close(fig)
    return outputs


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", type=Path, required=True,
                        help="report.json from scripts/run_algorithm_diagnostics.py")
    parser.add_argument("--output-dir", type=Path, default=Path("generated_figures/diagnostics"))
    args = parser.parse_args()
    source = args.report.read_bytes()
    report = json.loads(source)
    outputs = create_diagnostic_figures(report, args.output_dir)
    provenance = {
        "source_report": str(args.report.resolve()),
        "source_sha256": hashlib.sha256(source).hexdigest(),
        "protocol": report["protocol"], "smoke": report.get("smoke"),
        "source_command_line": report.get("command_line"),
        "interpretation": "Empirical clean-target errors in named cases; no breakdown guarantee.",
        "aggregation": "Arithmetic mean of reported RMSE over independent data seeds within each condition and policy; no error bars.",
        "outputs": [path.name for path in outputs],
    }
    (args.output_dir / "figure_provenance.json").write_text(json.dumps(provenance, indent=2) + "\n")
    print(f"Saved {len(outputs)} diagnostic exports to {args.output_dir}")


if __name__ == "__main__":
    main()
